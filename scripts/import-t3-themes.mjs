#!/usr/bin/env node
// Read a local upstream checkout without executing its TypeScript.
import fs from "node:fs";
import process from "node:process";
import console from "node:console";
import path from "node:path";
import { execFileSync } from "node:child_process";
import ts from "typescript";

const upstream = process.argv[2];
if (!upstream)
  throw new Error("Usage: node scripts/import-t3-themes.mjs /path/to/t3code");
const relative = "packages/shared/src/themePalettes.ts";
const source = ts.createSourceFile(
  relative,
  fs.readFileSync(path.join(upstream, relative), "utf8"),
  ts.ScriptTarget.Latest,
  true,
);
function literal(node) {
  if (ts.isStringLiteral(node)) return node.text;
  if (node.kind === ts.SyntaxKind.TrueKeyword) return true;
  if (node.kind === ts.SyntaxKind.FalseKeyword) return false;
  if (ts.isObjectLiteralExpression(node))
    return Object.fromEntries(
      node.properties.map((p) => {
        if (!ts.isPropertyAssignment(p))
          throw new Error("Unsupported upstream property");
        return [p.name.text, literal(p.initializer)];
      }),
    );
  throw new Error(
    "Unsupported upstream expression; review source before importing",
  );
}
const names = [
  "T3_CODE_LIGHT_THEME_COLORS",
  "T3_CODE_DARK_THEME_COLORS",
  "T3_CHAT_THEME",
  "GROVE_THEME",
  "OCEAN_THEME",
  "EMBER_THEME",
  "IRIS_THEME",
];
const values = new Map();
for (const statement of source.statements) {
  if (!ts.isVariableStatement(statement)) continue;
  for (const declaration of statement.declarationList.declarations) {
    if (names.includes(declaration.name.text))
      values.set(declaration.name.text, literal(declaration.initializer));
  }
}
if (values.size !== names.length)
  throw new Error("Upstream theme inventory changed");
const themes = [
  { id: "t3-code", light: values.get(names[0]), dark: values.get(names[1]) },
  ...names.slice(2).map((name) => {
    const theme = values.get(name);
    if (theme.appearance !== "light" || !theme.variants?.dark)
      throw new Error("Missing appearance variant");
    return { id: theme.id, light: theme.colors, dark: theme.variants.dark };
  }),
];
// Map upstream semantic roles onto shadcn's component tokens. No color guessing.
const roles = {
  background: "canvas",
  foreground: "text",
  card: "surface",
  "card-foreground": "text",
  popover: "surfaceOverlay",
  "popover-foreground": "text",
  primary: "accent",
  "primary-foreground": "accentForeground",
  secondary: "secondary",
  "secondary-foreground": "secondaryForeground",
  muted: "muted",
  "muted-foreground": "mutedForeground",
  accent: "accentSurface",
  "accent-foreground": "accentSurfaceForeground",
  destructive: "errorForeground",
  border: "border",
  input: "input",
  ring: "focus",
  sidebar: "sidebar",
  "sidebar-foreground": "sidebarForeground",
  "sidebar-primary": "accent",
  "sidebar-primary-foreground": "accentForeground",
  "sidebar-accent": "sidebarRowHover",
  "sidebar-accent-foreground": "sidebarForeground",
  "sidebar-border": "sidebarBorder",
  "sidebar-ring": "focus",
};
const commit = execFileSync("git", ["-C", upstream, "rev-parse", "HEAD"], {
  encoding: "utf8",
}).trim();
let css = `/* Adapted from pingdotgg/t3code ${commit}\n * ${relative}; MIT, Copyright (c) 2026 T3 Tools Inc.\n * See THIRD_PARTY_NOTICES.md. Generated by scripts/import-t3-themes.mjs.\n */\n`;
for (const theme of themes)
  for (const mode of ["light", "dark"]) {
    const appearance = mode === "dark" ? ".dark" : "";
    css += `:root${appearance}[data-color-theme="${theme.id}"] {\n`;
    for (const [token, role] of Object.entries(roles)) {
      const color = theme[mode][role];
      if (
        typeof color !== "string" ||
        !/^(#[\da-f]{6}|oklch\([\d. %]+\))$/i.test(color)
      )
        throw new Error(`Unexpected color: ${color}`);
      css += `  --${token}: ${color};\n`;
    }
    css += "}\n";
  }
fs.writeFileSync("src/lib/t3-themes.generated.css", css);
console.log(
  `Imported ${themes.length} palettes × 2 appearances from ${commit}`,
);
