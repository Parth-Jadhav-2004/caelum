"""Generate frontend configuration types from the Python dataclasses."""

import json
from dataclasses import fields
from pathlib import Path

from caelum.config import STT, App, Cleanup, Desktop
from caelum.ipc_contract import METHODS, STATUS

root = Path(__file__).resolve().parents[1]
lines = ["// Generated by scripts/generate-contracts.py; do not edit."]
for cls in (App, STT, Cleanup, Desktop):
    lines.append(f"export interface {cls.__name__}Config {{")
    for field in fields(cls):
        kind = {str: "string", int: "number", float: "number", bool: "boolean"}.get(
            field.type, "string | number | null"
        )
        lines.append(f"  {field.name}: {kind}")
    lines.append("}")
lines.append(
    "export interface Config { app: AppConfig; stt: STTConfig; cleanup: CleanupConfig; desktop: DesktopConfig }"
)
(root / "src/lib/config.generated.ts").write_text("\n".join(lines) + "\n")

# Runtime descriptors share the exact source used at the Python boundary.

(root / "src/lib/ipc-contract.generated.json").write_text(
    json.dumps({"methods": METHODS, "status": STATUS}, indent=2) + "\n"
)
